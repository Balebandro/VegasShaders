"""effects_index.py <repo root>: writes src/effects/INDEX.md, one line per effect folder (2026-11-02, modular restructure).
Re-run after adding, removing or renaming an effect folder."""
import os, re, sys
root = os.path.abspath(sys.argv[1]); os.chdir(root)
E = 'src/effects'
defaults = open('resource/VegasShaders.defaults.toml', encoding='utf-8').read()
rows = []
for name in sorted(d for d in os.listdir(E) if os.path.isdir(os.path.join(E, d))):
    d = os.path.join(E, name)
    on = re.search(r'^\[_?Shaders\.' + re.escape(name) + r'\.Status\]\s*\nEnabled\s*=\s*(\w+)', defaults, re.M | re.I)
    readme = os.path.exists(os.path.join(d, 'README.md'))
    shaders = 0
    if os.path.exists(os.path.join(d, 'SHADERS.txt')):
        shaders = sum(1 for l in open(os.path.join(d, 'SHADERS.txt'), encoding='utf-8') if l.strip() and not l.startswith('#'))
    sections = 0
    if os.path.exists(os.path.join(d, 'defaults.toml')):
        sections = sum(1 for l in open(os.path.join(d, 'defaults.toml'), encoding='utf-8') if l.startswith('['))
    purpose = ''
    if readme:
        txt = open(os.path.join(d, 'README.md'), encoding='utf-8').read()
        m = re.search(r'##\s*1\.?\s*Purpose\s*\n+(.+?)(?:\n\n|\n#)', txt, re.S)
        if m: purpose = ' '.join(m.group(1).split())[:160]
    code = ', '.join(sorted(f for f in os.listdir(d) if f.endswith(('.cpp', '.h'))))
    rows.append(f'| [{name}]({name}/) | {(on.group(1) if on else "-")} | {"yes" if readme else "-"} | {shaders} | {sections} | {code} | {purpose} |')
with open(os.path.join(E, 'INDEX.md'), 'w', encoding='utf-8', newline='\n') as f:
    f.write('# Effects index\n\nOne folder per effect: its C++, `README.md` (what it does, inputs, settings, passes, edge cases, Vulkan, look; read it '
            'before changing the effect and update it in the same change), `defaults.toml` (its settings defaults: `tools/defaults_tool.py merge` '
            'builds the one defaults file from these; `check` verifies) and `SHADERS.txt` (its shader files, which stay in `src/hlsl/NewVegas`, the '
            'game\'s layout). The frame order is in `src/core/EffectChain.cpp`. Generated by `tools/effects_index.py`.\n\n')
    f.write('| Effect | On by default | Doc | Shader files | Settings sections | C++ | Purpose |\n|---|---|---|---|---|---|---|\n')
    f.write('\n'.join(rows) + '\n')
print(len(rows), 'effects indexed')
