"""make_folders.py <repo root>   (2026-11-02, modular restructure phase B)

Moves every effect's C++ into src/effects/<Folder>/ (git mv), rewrites every #include in src/ so it still points at the same file,
updates the project files, and gives each folder its README.md (the effect's spec from rw-tools/specs, when there is one) and
SHADERS.txt (the shader files the effect's runtime loads; the shaders themselves stay where the game loads them from).
Shared files (Effects.h, Animator.*) stay in src/effects/.
"""
import os, re, subprocess, sys, shutil

root = os.path.abspath(sys.argv[1]); os.chdir(root)
EFFECTS = 'src/effects'
SPECS = r'specs'
STAY = {'Effects.h', 'Animator.cpp', 'Animator.h'}
# helper files that belong to another effect's folder; folder names follow the [Shaders.<Name>] settings section where they differ
FOLDER_OF = {
    'BloodFlowBoxes': 'BloodFlow', 'BloodFluid': 'BloodFlow', 'BodycamAudio': 'Bodycam', 'BounceLightMath': 'BounceLight',
    'LUTFile': 'LUT', 'LUTIdentity': 'LUT', 'TAAFSR': 'TAA', 'TAAUpscale': 'TAA', 'VolumetricSmokeQuads': 'VolumetricSmoke',
    'GpuGrass': 'Grass', 'GrassCollision': 'Grass', 'PhysSkyModel': 'Sky', 'LandHeights': 'Terrain',
    'Rain': 'Precipitations', 'ShadowsExterior': 'ShadowsExteriors',
}

def git(*a):
    r = subprocess.run(['git', '-c', 'diff.ignoreSubmodules=all', *a], capture_output=True, text=True)
    if r.returncode: sys.exit('git ' + ' '.join(a) + ': ' + r.stderr)
    return r.stdout

# 1. the move plan: old path -> new path (repo-relative, forward slashes)
plan = {}
for f in sorted(os.listdir(EFFECTS)):
    p = f'{EFFECTS}/{f}'
    if not os.path.isfile(p) or f in STAY: continue
    stem = os.path.splitext(f)[0]
    folder = FOLDER_OF.get(stem, stem)
    plan[p] = f'{EFFECTS}/{folder}/{f}'

# 2. every source file in src/ (before the move), its includes resolved against the OLD layout
SRC_EXT = ('.cpp', '.h', '.hpp', '.inl')
files = [f for f in git('ls-files', 'src').split('\n') if f.endswith(SRC_EXT)]
INC = re.compile(r'(#\s*include\s*")([^"]+)(")')
fixes = {}
for f in files:
    text = open(f, encoding='utf-8', errors='surrogateescape', newline='').read()
    new_loc = plan.get(f, f)
    def rewrite(m):
        target = os.path.normpath(os.path.join(os.path.dirname(f), m.group(2))).replace('\\', '/')
        if not os.path.exists(target):
            return m.group(0)                                   # resolved through an include directory or not ours: unchanged
        target_new = plan.get(target, target)
        rel = os.path.relpath(target_new, os.path.dirname(new_loc)).replace('\\', '/')
        return m.group(1) + rel + m.group(3)
    out = INC.sub(rewrite, text)
    if out != text: fixes[f] = out

# 3. move, then write the rewritten includes at the new locations
for old, new in plan.items():
    os.makedirs(os.path.dirname(new), exist_ok=True)
    git('mv', old, new)
for f, text in fixes.items():
    open(plan.get(f, f), 'w', encoding='utf-8', errors='surrogateescape', newline='').write(text)

# 4. project files: ..\src\effects\X -> ..\src\effects\Folder\X
for proj in ['NewVegasReloaded/NewVegasReloaded.vcxproj', 'NewVegasReloaded/NewVegasReloaded.vcxproj.filters']:
    if not os.path.exists(proj): continue
    s = open(proj, encoding='utf-8-sig', newline='').read()
    for old, new in plan.items():
        s = s.replace('..\\' + old.replace('/', '\\') + '"', '..\\' + new.replace('/', '\\') + '"')
    open(proj, 'w', encoding='utf-8-sig', newline='').write(s)

# 5. README.md (the spec) and SHADERS.txt per folder
folders = sorted({os.path.dirname(n) for n in plan.values()})
hlsl = [f for f in git('ls-files', 'src/hlsl/NewVegas').split('\n') if f]
for d in folders:
    name = os.path.basename(d)
    spec = os.path.join(SPECS, name + '.md')
    if os.path.exists(spec) and not os.path.exists(f'{d}/README.md'):
        shutil.copyfile(spec, f'{d}/README.md')
    own = [h for h in hlsl if re.search(r'/(Effects|Compute)/' + re.escape(name) + r'([A-Z][A-Za-z]*)?(-[^/]*)?\.(fx\.hlsl|frag|comp|glsl|spv)$', h)]
    if own:
        with open(f'{d}/SHADERS.txt', 'w', encoding='utf-8', newline='\n') as h:
            h.write(f'# The shader files the {name} effect loads (they stay where the game loads them from: src/hlsl/NewVegas mirrors\n'
                    f'# Data\\Shaders\\VegasShaders). Generated by rw-tools/modular/make_folders.py; keep it up to date by hand.\n')
            h.write('\n'.join(own) + '\n')
print(f'moved {len(plan)} files into {len(folders)} folders; includes rewritten in {len(fixes)} files')
